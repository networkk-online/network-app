
-- Create a table for suggested/featured content for new users
CREATE TABLE public.featured_posts (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  content TEXT NOT NULL,
  media_url TEXT,
  author_name TEXT NOT NULL,
  author_avatar TEXT,
  author_location TEXT,
  likes_count INTEGER DEFAULT 0,
  comments_count INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  is_active BOOLEAN DEFAULT true
);

-- Enable RLS
ALTER TABLE public.featured_posts ENABLE ROW LEVEL SECURITY;

-- Anyone can view featured posts
CREATE POLICY "Anyone can view featured posts"
ON public.featured_posts
FOR SELECT
USING (is_active = true);

-- Only admins can manage featured posts
CREATE POLICY "Admins can manage featured posts"
ON public.featured_posts
FOR ALL
USING (has_role(auth.uid(), 'admin'::app_role));

